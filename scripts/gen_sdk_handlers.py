"""Bind the analyzer's SDK matches (sceSif*/sceCd*/scePad*/sceMc*...) to the runtime's native handlers.

Generated calls go through the function table, so overriding the table slots at startup replaces the
guest SDK code without regenerating the AOT sources. Names listed in config/sdk-handlers-exclude.txt
keep their translated guest implementation.
"""
import re
import tomllib
from pathlib import Path

root = Path(__file__).resolve().parents[1]
call_list = (root.parent / 'third_party/PS2Recomp/ps2xRuntime/include/ps2_call_list.h').read_text()


def names(macro):
    body = re.search(rf'#define {macro}\(X\)(.*?)(?:\n#define|\Z)', call_list, re.S)[1]
    return set(re.findall(r'X\((\w+)\)', body))


syscalls, stubs = names('PS2_SYSCALL_LIST'), names('PS2_STUB_LIST')
exclude_path = root / 'config/sdk-handlers-exclude.txt'
exclude = {l.split('#')[0].strip() for l in exclude_path.read_text().splitlines()} if exclude_path.exists() else set()
matches = tomllib.loads((root / 'config/analyzer-heuristic.toml').read_text())['general']['stubs']
# SDK functions the analyzer missed, identified by hand ('name@0xADDR' per line, # comments).
extra_path = root / 'config/sdk-handlers-extra.txt'
if extra_path.exists():
    matches += [l.split('#')[0].strip() for l in extra_path.read_text().splitlines() if l.split('#')[0].strip()]
ghidra_wrappers = {int(s.split('@')[1], 16) for s in
                   tomllib.loads((root / 'config/ben10-af.toml').read_text())['general']['stubs']}

wrappers, entries, skipped = [], [], []
for match in matches:
    name, addr = match.split('@')
    addr = int(addr, 16)
    if name in exclude or addr in ghidra_wrappers:
        skipped.append(match)
        continue
    # Like the generator: '_sceX' binds to sceX unless the internal variant has a different ABI.
    if name in ('_sceSifSendCmd', '_sceSifCmdIntrHdlr'):
        skipped.append(match)
        continue
    name = name.lstrip('_') if name.lstrip('_') in syscalls | stubs else name
    ns = 'ps2_syscalls' if name in syscalls else 'ps2_stubs' if name in stubs else None
    if ns is None:
        skipped.append(match)
        continue
    fn = f'Ben10Sdk_{name}_0x{addr:x}'
    wrappers.append(f'static void {fn}(uint8_t* rdram, R5900Context* ctx, PS2Runtime* runtime) {{\n'
                    f'    ctx->pc = getRegU32(ctx, 31);\n    {ns}::{name}(rdram, ctx, runtime);\n}}')
    entries.append(f'    {{0x{addr:x}u, {fn}}},')

out = root / 'project/sdk-handlers.inc'
out.write_text('// Generated by scripts/gen_sdk_handlers.py; do not edit.\n' + '\n'.join(wrappers) +
               '\nstatic const Ben10TableEntry kBen10SdkHandlers[] = {\n' + '\n'.join(entries) + '\n};\n')
print(f'{len(entries)} SDK handlers bound, {len(skipped)} skipped: {skipped}')
