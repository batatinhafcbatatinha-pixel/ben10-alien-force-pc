"""Use this game's Ghidra map; keep SDK signature guesses separate for review."""
import csv
import hashlib
import json
import re
from pathlib import Path
import tomllib

root = Path(__file__).resolve().parents[1]
config = root / 'config'
g = tomllib.loads((config / 'ben10-af.toml').read_text())['general']
a = tomllib.loads((config / 'analyzer-heuristic.toml').read_text())['general']
map_path = config / 'ghidra-functions-only.csv'
rows = list(csv.DictReader(map_path.open()))
if not rows:
    raise SystemExit('Empty Ghidra function map; refusing to generate config')
q = lambda value: json.dumps(str(value).replace('\\', '/'))
lines = ['# Generated by scripts/prepare_config.py; SDK signature candidates are not applied.', '[general]',
         f'input = {q(root / "analysis/disc/SLUS_218.15")}',
         f'output = {q(root / "project/runner")}',
         f'ghidra_output = {q(map_path)}',
         'single_file_output = false', 'low_memory_mode = true', 'output_worker_threads = 1',
         'patch_syscalls = false', 'patch_cop0 = true', 'patch_cache = true', 'stubs = [']
lines += [f'  {q(s)},' for s in g.get('stubs', [])]
lines += [']', 'skip = []']
(config / 'recomp.toml').write_text('\n'.join(lines) + '\n')
report = {'local_record_id': 'ben10-ghidra-map-20261025',
          'elf_sha256': hashlib.sha256((root / 'analysis/disc/SLUS_218.15').read_bytes()).hexdigest(),
          'map_records': len(rows), 'ghidra_stubs_applied': g.get('stubs', []),
          'sdk_signature_candidates_not_applied': a.get('stubs', []),
          'limitations': ['Static function boundaries and wrapper classifications; no execution validation.',
                         'SDK signature matches require review before replacement with runtime handlers.',
                         'VU overlays and indirect targets may be incomplete.']}
log_path = root / 'analysis/ghidra-export.log'
if log_path.exists():
    log = log_path.read_text(errors='replace')
    match = re.search(r'Exported (\d+) functions and (\d+) executable labels', log)
    if match:
        report.update(ghidra_functions=int(match[1]), ghidra_executable_labels=int(match[2]))
    report['ghidra_errors'] = [line for line in log.splitlines() if 'ERROR ' in line]
    if 'is not byte-mapped, skipping' in log:
        report['limitations'].append('Ghidra skipped non-byte-mapped DVP overlay blocks; VU translation is not established.')
(root / 'analysis/config-evidence.json').write_text(json.dumps(report, indent=2) + '\n')
print(f'{len(rows)} map records; {len(g.get("stubs", []))} Ghidra wrappers; SDK candidates retained separately')
